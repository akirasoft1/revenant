#!/usr/bin/env node
'use strict';
// Real-model voice smoke test for Star Citizen knowledge (sc-knowledge)
// function calling on the Gemini Live voice path (design/plan
// 2026-09-26-star-citizen-knowledge, Task 13). No Discord, no humans: it
// opens one real Converse session per question against the voice sidecar,
// streams a synthesized single-speaker utterance, and asserts the model's
// OUTPUT TRANSCRIPT actually contains the fact that only a live sc_* tool
// call could have produced. That is the one thing unit tests can't cover --
// it needs a live Gemini Live session with SC declarations attached and a
// reachable sc-knowledge service behind the sidecar.
//
// Prerequisites:
//   - Port-forward the voice sidecar:
//       kubectl port-forward svc/discord-article-bot-voice 50051:50051 -n discord-article-bot &
//   - The voice sidecar must be running with SC_KNOWLEDGE_ENABLED=true and a
//     reachable SC_KNOWLEDGE_URL (see CLAUDE.md "Star Citizen Knowledge").
//   - This script only observes whether the ANSWER is correct. It does NOT
//     itself confirm an sc_* tool was actually invoked (vs. the model
//     answering from parametric knowledge) -- cross-check the sidecar logs
//     for a "voice: tool_call" line per question when reviewing results.
//
// Usage:
//   node scripts/smoke-voice-sc.js
//
// With no args, uses six voice-fixtures/sc-*.wav clips (generated by
// scripts/gen-test-voices.js, which needs GEMINI_API_KEY -- run
// automatically here if voice-fixtures/ doesn't already have all six).
//
// Env overrides:
//   VOICE_GRPC_ADDR         sidecar address (default 127.0.0.1:50051, i.e. a port-forward)
//   SMOKE_TRANSCRIPT_WAIT_MS  how long to keep collecting output_transcript
//                             text after the audio ends (default 45000)
//
// CITATION SILENT (critical, since 2026-10-10): across every question, no
// output transcript may contain a spoken bracketed numeric citation like
// "[1]" or "[1, 3]" (gemini-live-2.5-flash read ~150 of these aloud in the
// model spike). Offending transcripts are printed in full.
//
// Exit code: non-zero if ANY of the six questions FAILs its check, if
// CITATION SILENT fails, or on a harness-level failure (can't connect, ffmpeg missing, fixture generation
// failed, etc).
//
// IMPORTANT: this script does NOT truncate any transcript it prints.

const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const VoiceClient = require('../services/VoiceClient');
const { findCitationLeaks } = require('./lib/voiceSmokeChecks');

const SAMPLE_RATE = 16000;
const FRAME_MS = 20;
const FRAME_BYTES = (SAMPLE_RATE * FRAME_MS) / 1000 * 2; // 640 bytes = 320 samples * 2 bytes (s16le)
const TRAILING_SILENCE_MS = 300; // small pad so the sidecar sees a natural pause before audio_stream_end

const FIXTURE_DIR = path.join(__dirname, '..', 'voice-fixtures');
const PROTO_PATH = path.join(__dirname, '..', 'proto', 'voice.proto');
const GEN_VOICES_SCRIPT = path.join(__dirname, 'gen-test-voices.js');

const ADDRESS = process.env.VOICE_GRPC_ADDR || '127.0.0.1:50051';
const HEALTH_TIMEOUT_MS = 8000;
const TRANSCRIPT_WAIT_MS = Number(process.env.SMOKE_TRANSCRIPT_WAIT_MS || 45000);

const SPEAKER = { userId: 'smoke-test-sc-speaker', displayName: 'Mike' };

// The five canonical SC questions (+ a sixth, tool-less mechanics question below) (wording matches agent-sidecar/eval/sc_eval_set.py
// "the four canonical questions" plus the fifth Scorpius ship-purchase check --
// ship/vehicle purchases were added to sc_find_item after that eval set was
// written). Each `check` is matched case-insensitively against the FULL
// concatenated output transcript for that question's session.
const QUESTIONS = [
  {
    id: 'v801-radar',
    file: 'sc-v801-radar.wav',
    text: 'Where can we purchase a V801-12 radar?',
    expectDesc: '"new babbage" or "omega"',
    check: (t) => t.includes('new babbage') || t.includes('omega'),
  },
  {
    id: 'shield-size2',
    file: 'sc-shield-size2.wav',
    text: 'What is the most powerful Size 2 shield generator?',
    expectDesc: '"fr-76" or "coverall" or "gorgon"',
    check: (t) => t.includes('fr-76') || t.includes('coverall') || t.includes('gorgon'),
  },
  {
    id: 'foxwell-rep',
    file: 'sc-foxwell-rep.wav',
    text: 'What is an optimal way to grind Foxwell Enforcement reputation?',
    expectDesc: '"foxwell" and one of "rank"/"reputation"/"mission"',
    check: (t) => t.includes('foxwell') && (t.includes('rank') || t.includes('reputation') || t.includes('mission')),
  },
  {
    id: 'mic-l5-routes',
    file: 'sc-mic-l5-routes.wav',
    text: 'What are some currently profitable trade routes from MIC-L5?',
    expectDesc: '"scrap" or "route"',
    check: (t) => t.includes('scrap') || t.includes('route'),
  },
  {
    id: 'scorpius-buy',
    file: 'sc-scorpius-buy.wav',
    text: 'Where can I buy a Scorpius?',
    expectDesc: '"new deal" or "lorville"',
    check: (t) => t.includes('new deal') || t.includes('lorville'),
  },
  {
    // A mechanics question no sc_* tool covers (2026-09-29 quantum-drive
    // dispute). The answer must engage NAV mode + the spooled quantum drive
    // instead of denying it; cross-check the sidecar's turn-complete line for
    // search_queries>0 (a "voice: web search (turn #K): ..." line) -- that is
    // the evidence it searched rather than answering from memory.
    id: 'nav-quantum',
    file: 'sc-nav-quantum.wav',
    text: 'In Star Citizen, why do I have to spool my quantum drive in NAV mode to go faster than my normal engines?',
    expectDesc: '"nav" and one of "spool"/"quantum"',
    check: (t) => t.includes('nav') && (t.includes('spool') || t.includes('quantum')),
  },
];

function hr(char = '-') { return char.repeat(70); }
function log(...args) { console.log(...args); }

function sleep(ms) { return new Promise((resolve) => setTimeout(resolve, ms)); }

function waitForEvent(emitter, eventName, timeoutMs) {
  return new Promise((resolve) => {
    let done = false;
    const timer = setTimeout(() => {
      if (done) return;
      done = true;
      resolve(false);
    }, timeoutMs);
    emitter.once(eventName, () => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      resolve(true);
    });
  });
}

// --- Audio decode/chunk (identical approach to scripts/smoke-voice-identity.js) ---

function decode16kMonoS16le(file) {
  return execFileSync('ffmpeg', [
    '-v', 'error', '-i', file,
    '-ac', '1', '-ar', String(SAMPLE_RATE),
    '-f', 's16le', '-acodec', 'pcm_s16le', 'pipe:1',
  ], { maxBuffer: 1 << 28 });
}

/** Split raw PCM into 20ms/640-byte frames, matching what the bot sends.
 * A trailing partial frame is zero-padded rather than dropped -- audio
 * quality of the last <20ms doesn't matter, but silently discarding it
 * would be a lie about "the whole clip was streamed." */
function chunkFrames(pcmBuf) {
  const frames = [];
  let off = 0;
  for (; off + FRAME_BYTES <= pcmBuf.length; off += FRAME_BYTES) {
    frames.push(pcmBuf.subarray(off, off + FRAME_BYTES));
  }
  const rem = pcmBuf.length - off;
  if (rem > 0) {
    const last = Buffer.alloc(FRAME_BYTES);
    pcmBuf.copy(last, 0, off);
    frames.push(last);
  }
  return frames;
}

function silenceFrames(ms) {
  const n = Math.round(ms / FRAME_MS);
  const frames = [];
  for (let i = 0; i < n; i++) frames.push(Buffer.alloc(FRAME_BYTES));
  return frames;
}

// --- Fixture resolution --------------------------------------------------

function resolveFixtures() {
  const needed = QUESTIONS.map((q) => q.file);
  const missing = () => needed.filter((f) => !fs.existsSync(path.join(FIXTURE_DIR, f)));

  let miss = missing();
  if (miss.length > 0) {
    log(`voice-fixtures/ is missing ${miss.length} SC fixture(s) (${miss.join(', ')}) -- generating with scripts/gen-test-voices.js (requires GEMINI_API_KEY)...\n`);
    const res = spawnSync(process.execPath, [GEN_VOICES_SCRIPT], { stdio: 'inherit' });
    if (res.status !== 0) {
      console.error('\nERROR: fixture generation failed (see output above).');
      console.error('Set GEMINI_API_KEY and retry: GEMINI_API_KEY=... node scripts/gen-test-voices.js');
      process.exit(1);
    }
    miss = missing();
  }
  if (miss.length > 0) {
    console.error(`ERROR: still missing SC fixture(s) after generation: ${miss.join(', ')}`);
    console.error('Check scripts/gen-test-voices.js CLIPS includes all six sc-*.wav entries.');
    process.exit(1);
  }
  return needed.map((f) => path.join(FIXTURE_DIR, f));
}

async function askQuestion(client, q, filePath) {
  log(`\n${hr('-')}\n${q.id}: "${q.text}"\n${hr('-')}`);

  log('  decoding to 16kHz mono s16le and chunking to 20ms/640B frames (ffmpeg)...');
  let frames;
  try {
    frames = chunkFrames(decode16kMonoS16le(filePath)).concat(silenceFrames(TRAILING_SILENCE_MS));
  } catch (e) {
    console.error(`  ERROR: ffmpeg decode failed: ${e.message}`);
    console.error('  Is ffmpeg installed and on PATH?');
    process.exit(1);
  }
  log(`  ${frames.length} frames (~${(frames.length * FRAME_MS / 1000).toFixed(1)}s incl. trailing pad)`);

  const session = client.converse();
  const outputTranscripts = [];
  let sawError = false;

  session.on('outputTranscript', (text) => {
    outputTranscripts.push(text);
    log(`  [output_transcript] "${text}"`);
  });
  session.on('turnComplete', () => log('  [turn_complete]'));
  session.on('interrupted', () => log('  [interrupted]'));
  session.on('error', (err) => {
    sawError = true;
    console.error(`  [error] ${err.message}`);
  });
  session.on('end', () => log('  [stream end]'));

  session.sendStart({
    userId: 'smoke-test-harness',
    userTag: 'smoke-test#0000',
    channelId: 'smoke-test-sc-channel',
    guildId: 'smoke-test-sc-guild',
    systemPrompt: 'You are a helpful, friendly voice assistant in a live Discord voice channel.',
    recallContext: '',
    voiceName: 'Puck',
    history: [],
  });
  session.sendSpeaker(SPEAKER);

  log(`  streaming ${frames.length} frames at 20ms cadence (real-time, matches the bot)...`);
  for (const f of frames) {
    session.sendAudio(f);
    // eslint-disable-next-line no-await-in-loop
    await sleep(FRAME_MS);
  }
  session.sendAudioStreamEnd();
  log('  sendAudioStreamEnd (finalize turn)');

  log(`  collecting output_transcript for up to ${TRANSCRIPT_WAIT_MS}ms after audio end...`);
  // Wait the full window rather than stopping at the first turn_complete:
  // an SC tool call adds latency (MCP round trip to sc-knowledge), and a
  // reply can also legitimately arrive as more than one turn_complete.
  await Promise.race([
    sleep(TRANSCRIPT_WAIT_MS),
    waitForEvent(session, 'error', TRANSCRIPT_WAIT_MS),
  ]);

  session.end();
  await waitForEvent(session, 'end', 3000);
  session.removeAllListeners();

  const fullText = outputTranscripts.join(' ');
  const pass = q.check(fullText.toLowerCase());
  log(`\n  Expected: ${q.expectDesc}`);
  log(`  Full transcript: ${outputTranscripts.length ? outputTranscripts.map((t) => `"${t}"`).join(' ') : '(none received)'}`);
  if (sawError) log('  NOTE: session reported at least one error event -- treat this result with that in mind.');
  log(`  VERDICT (${q.id}): ${pass ? 'PASS' : 'FAIL'}`);

  const citationLeaks = findCitationLeaks(outputTranscripts);
  if (citationLeaks.length) {
    log(`  CITATION LEAK (${q.id}): ${citationLeaks.length} transcript(s) spoke a bracketed citation:`);
    for (const t of citationLeaks) log(`    - "${t}"`);
  }

  return { id: q.id, text: q.text, pass, transcript: fullText, sawError, citationLeaks };
}

async function main() {
  log(hr('='));
  log('Star Citizen knowledge voice smoke test (Layer 4 -- real model, no Discord, no humans)');
  log('Reminder: this checks the ANSWER only. Cross-check sidecar logs for "voice: tool_call"');
  log('per question to confirm an sc_* tool actually fired (vs. parametric-knowledge luck).');
  log(hr('='));

  const files = resolveFixtures();
  log('\nFixtures:');
  QUESTIONS.forEach((q, i) => log(`  ${q.id} -> ${files[i]}`));

  log(`\nConnecting to sidecar at ${ADDRESS} (health-polling)...`);
  const client = new VoiceClient({
    address: ADDRESS,
    protoPath: PROTO_PATH,
    healthIntervalMs: 1000,
    unhealthyThresholdMs: 5000,
    healthDeadlineMs: 2000,
  });

  const healthyDeadline = Date.now() + HEALTH_TIMEOUT_MS;
  let healthy = false;
  while (Date.now() < healthyDeadline) {
    if (client.isHealthy()) { healthy = true; break; }
    // eslint-disable-next-line no-await-in-loop
    await sleep(250);
  }
  if (!healthy) {
    console.error(`\nERROR: sidecar at ${ADDRESS} did not report healthy within ${HEALTH_TIMEOUT_MS}ms.`);
    console.error('Is the port-forward running?');
    console.error('  kubectl port-forward svc/discord-article-bot-voice 50051:50051 -n discord-article-bot &');
    console.error('Is SC_KNOWLEDGE_ENABLED=true set on the voice sidecar deployment?');
    client.close();
    process.exit(1);
  }
  log('  sidecar healthy.');

  const results = [];
  for (let i = 0; i < QUESTIONS.length; i++) {
    // eslint-disable-next-line no-await-in-loop
    const r = await askQuestion(client, QUESTIONS[i], files[i]);
    results.push(r);
  }

  client.close();

  log(`\n${hr('=')}\nSUMMARY\n${hr('=')}`);
  for (const r of results) {
    log(`  ${r.pass ? 'PASS' : 'FAIL'}  ${r.id.padEnd(16)} "${r.text}"`);
  }
  const failed = results.filter((r) => !r.pass);
  const citationOffenders = results.filter((r) => r.citationLeaks.length > 0);
  const citationSilentPass = citationOffenders.length === 0;
  log(`  ${citationSilentPass ? 'PASS' : 'FAIL'}  CITATION SILENT (critical) -- no spoken "[1]" / "[1, 3]" in any answer`);
  for (const r of citationOffenders) {
    for (const t of r.citationLeaks) log(`        ${r.id}: "${t}"`);
  }
  log(hr('='));
  log(`\n${results.length - failed.length}/${results.length} passed.`);
  if (failed.length > 0) {
    log(`FAILED: ${failed.map((r) => r.id).join(', ')}`);
  }
  log('\nReminder: also confirm sidecar logs show a "voice: tool_call" line per question --');
  log('a PASS here only proves the answer was right, not that an sc_* tool produced it.');

  if (!citationSilentPass) {
    log(`CITATION SILENT FAILED: ${citationOffenders.map((r) => r.id).join(', ')}`);
  }
  process.exit(failed.length > 0 || !citationSilentPass ? 1 : 0);
}

main().catch((e) => {
  console.error('\nFATAL: smoke test crashed:');
  console.error(e && e.stack ? e.stack : e);
  process.exit(1);
});
