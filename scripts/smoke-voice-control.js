#!/usr/bin/env node
'use strict';
// Real-model voice smoke test for the spoken voice-control commands (design
// docs/superpowers/specs/2026-09-27-voice-control-commands-design.md): "go
// quiet for two minutes" and "thanks jarvis, that's all". No Discord, no
// humans: it opens one real Converse session per fixture against the voice
// sidecar, streams a synthesized single-speaker utterance, and asserts the
// sidecar emits a `control` VoiceServerEvent (proto/voice.proto field 7)
// naming the right action -- the thing unit tests can't cover, because it
// needs a live Gemini Live session with the end_conversation/go_quiet
// function declarations attached and the model actually choosing to call one.
//
// This exercises the MODEL-TOOL path ONLY. The phrase backstop
// (services/voice/controlPhrases.js, matched against the bot's own input
// transcript) is bot-side pure logic with no model or network dependency --
// it is covered by __tests__/services/voice/controlPhrases.test.js, not
// this script.
//
// A third, NEGATIVE fixture ("hey jarvis, that's all I know about shields,
// what do you think?") asserts NO control event arrives. This exists
// because of a real review finding (Task 1 ruling, see
// .superpowers/sdd/2026-09-27-voice-control-commands/progress.md): the
// end_conversation tool description cites "that's all" as an example
// trigger phrase, which risks the model firing it on a sentence that merely
// CONTAINS "that's all" mid-utterance rather than ending the conversation
// with it. If this fixture FAILs (a control event arrives), the fix is to
// tighten the tool description in the sidecar, not this script.
//
// ORDERING CHECK (quiet/end fixtures): the bot executes a command only once
// the model's reply turn has produced OUTPUT and then completed, because Live
// emits a bare turn_complete for the tool-call turn itself (no audio) before
// the confirmation is spoken. This script records the event timeline and
// FAILs a positive fixture unless model audio arrives AFTER the control event
// and BEFORE the final turn_complete -- i.e. a spoken confirmation exists for
// the bot to wait for. The timeline is printed either way.
//
// Prerequisites:
//   - Port-forward the voice sidecar:
//       kubectl port-forward svc/discord-article-bot-voice 50051:50051 -n discord-article-bot &
//   - The voice sidecar must be running with VOICE_CONTROL_TOOLS_ENABLED=true
//     (the default) so end_conversation/go_quiet are declared to the Live
//     model at all.
//
// Usage:
//   node scripts/smoke-voice-control.js
//
// With no args, uses three voice-fixtures/ctl-*.wav clips (generated by
// scripts/gen-test-voices.js, which needs GEMINI_API_KEY -- run
// automatically here if voice-fixtures/ doesn't already have all three).
//
// Env overrides:
//   VOICE_GRPC_ADDR          sidecar address (default 127.0.0.1:50051, i.e. a port-forward)
//   SMOKE_CONTROL_WAIT_MS    how long to keep collecting events after the audio ends (default 45000)
//
// Exit code: non-zero if ANY of the three fixtures FAILs its check, or on a
// harness-level failure (can't connect, ffmpeg missing, fixture generation
// failed, etc).
//
// IMPORTANT: this script does NOT truncate any transcript it prints.

const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const VoiceClient = require('../services/VoiceClient');

const SAMPLE_RATE = 16000;
const FRAME_MS = 20;
const FRAME_BYTES = (SAMPLE_RATE * FRAME_MS) / 1000 * 2; // 640 bytes = 320 samples * 2 bytes (s16le)
const TRAILING_SILENCE_MS = 300; // small pad so the sidecar sees a natural pause before audio_stream_end

const FIXTURE_DIR = path.join(__dirname, '..', 'voice-fixtures');
const PROTO_PATH = path.join(__dirname, '..', 'proto', 'voice.proto');
const GEN_VOICES_SCRIPT = path.join(__dirname, 'gen-test-voices.js');

const ADDRESS = process.env.VOICE_GRPC_ADDR || '127.0.0.1:50051';
const HEALTH_TIMEOUT_MS = 8000;
const CONTROL_WAIT_MS = Number(process.env.SMOKE_CONTROL_WAIT_MS || 45000);

const SPEAKER = { userId: 'smoke-test-control-speaker', displayName: 'Mike' };

// action: null means "no control event expected" (the negative fixture).
const FIXTURES = [
  {
    id: 'ctl-quiet',
    file: 'ctl-quiet.wav',
    text: 'Hey Jarvis, go quiet for two minutes.',
    expectDesc: 'control event action="quiet" seconds=120 (2 min), then confirmation audio, then turn_complete',
    check: (events) => events.some((e) => e.action === 'quiet' && e.seconds === 120),
    checkOrdering: true,
  },
  {
    id: 'ctl-end',
    file: 'ctl-end.wav',
    text: "Thanks Jarvis, that's all.",
    expectDesc: 'control event action="end", then confirmation audio, then turn_complete',
    check: (events) => events.some((e) => e.action === 'end'),
    checkOrdering: true,
  },
  {
    id: 'ctl-negative',
    file: 'ctl-negative.wav',
    text: "Hey Jarvis, that's all I know about shields, what do you think?",
    expectDesc: 'NO control event (mid-sentence "that\'s all" must not end the conversation)',
    check: (events) => events.length === 0,
    checkOrdering: false,
  },
];

/**
 * timeline: [{type: 'control'|'audio'|'turn_complete', ...}] in arrival order.
 * OK iff there is a control event, some audio after the first control event,
 * and a turn_complete after that audio (the final turn_complete).
 */
function checkOrdering(timeline) {
  const ci = timeline.findIndex((e) => e.type === 'control');
  if (ci < 0) return { ok: false, why: 'no control event' };
  const ai = timeline.findIndex((e, i) => i > ci && e.type === 'audio');
  if (ai < 0) return { ok: false, why: 'no model audio arrived after the control event (no spoken confirmation)' };
  let lastTc = -1;
  timeline.forEach((e, i) => { if (e.type === 'turn_complete') lastTc = i; });
  if (lastTc < ai) return { ok: false, why: 'the final turn_complete did not come after the confirmation audio' };
  const bare = timeline.slice(ci + 1, ai).filter((e) => e.type === 'turn_complete').length;
  return { ok: true, why: `confirmation audio after control; ${bare} bare turn_complete(s) between control and first audio` };
}

function hr(char = '-') { return char.repeat(70); }
function log(...args) { console.log(...args); }

function sleep(ms) { return new Promise((resolve) => setTimeout(resolve, ms)); }

function waitForEvent(emitter, eventName, timeoutMs) {
  return new Promise((resolve) => {
    let done = false;
    const timer = setTimeout(() => {
      if (done) return;
      done = true;
      resolve(false);
    }, timeoutMs);
    emitter.once(eventName, () => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      resolve(true);
    });
  });
}

// --- Audio decode/chunk (identical approach to scripts/smoke-voice-sc.js) ---

function decode16kMonoS16le(file) {
  return execFileSync('ffmpeg', [
    '-v', 'error', '-i', file,
    '-ac', '1', '-ar', String(SAMPLE_RATE),
    '-f', 's16le', '-acodec', 'pcm_s16le', 'pipe:1',
  ], { maxBuffer: 1 << 28 });
}

/** Split raw PCM into 20ms/640-byte frames, matching what the bot sends.
 * A trailing partial frame is zero-padded rather than dropped -- audio
 * quality of the last <20ms doesn't matter, but silently discarding it
 * would be a lie about "the whole clip was streamed." */
function chunkFrames(pcmBuf) {
  const frames = [];
  let off = 0;
  for (; off + FRAME_BYTES <= pcmBuf.length; off += FRAME_BYTES) {
    frames.push(pcmBuf.subarray(off, off + FRAME_BYTES));
  }
  const rem = pcmBuf.length - off;
  if (rem > 0) {
    const last = Buffer.alloc(FRAME_BYTES);
    pcmBuf.copy(last, 0, off);
    frames.push(last);
  }
  return frames;
}

function silenceFrames(ms) {
  const n = Math.round(ms / FRAME_MS);
  const frames = [];
  for (let i = 0; i < n; i++) frames.push(Buffer.alloc(FRAME_BYTES));
  return frames;
}

// --- Fixture resolution --------------------------------------------------

function resolveFixtures() {
  const needed = FIXTURES.map((f) => f.file);
  const missing = () => needed.filter((f) => !fs.existsSync(path.join(FIXTURE_DIR, f)));

  let miss = missing();
  if (miss.length > 0) {
    log(`voice-fixtures/ is missing ${miss.length} control fixture(s) (${miss.join(', ')}) -- generating with scripts/gen-test-voices.js (requires GEMINI_API_KEY)...\n`);
    const res = spawnSync(process.execPath, [GEN_VOICES_SCRIPT], { stdio: 'inherit' });
    if (res.status !== 0) {
      console.error('\nERROR: fixture generation failed (see output above).');
      console.error('Set GEMINI_API_KEY and retry: GEMINI_API_KEY=... node scripts/gen-test-voices.js');
      process.exit(1);
    }
    miss = missing();
  }
  if (miss.length > 0) {
    console.error(`ERROR: still missing control fixture(s) after generation: ${miss.join(', ')}`);
    console.error('Check scripts/gen-test-voices.js CLIPS includes all three ctl-*.wav entries.');
    process.exit(1);
  }
  return needed.map((f) => path.join(FIXTURE_DIR, f));
}

async function runFixture(client, fx, filePath) {
  log(`\n${hr('-')}\n${fx.id}: "${fx.text}"\n${hr('-')}`);

  log('  decoding to 16kHz mono s16le and chunking to 20ms/640B frames (ffmpeg)...');
  let frames;
  try {
    frames = chunkFrames(decode16kMonoS16le(filePath)).concat(silenceFrames(TRAILING_SILENCE_MS));
  } catch (e) {
    console.error(`  ERROR: ffmpeg decode failed: ${e.message}`);
    console.error('  Is ffmpeg installed and on PATH?');
    process.exit(1);
  }
  log(`  ${frames.length} frames (~${(frames.length * FRAME_MS / 1000).toFixed(1)}s incl. trailing pad)`);

  const session = client.converse();
  const outputTranscripts = [];
  const controlEvents = [];
  const timeline = [];
  const t0 = Date.now();
  let audioChunksThisTurn = 0;
  let sawError = false;

  session.on('audio', (buf) => {
    timeline.push({ type: 'audio', t: Date.now() - t0 });
    if (audioChunksThisTurn === 0) log(`  [audio] first model audio chunk of this turn (+${Date.now() - t0}ms, ${buf.length} bytes)`);
    audioChunksThisTurn++;
  });
  session.on('outputTranscript', (text) => {
    outputTranscripts.push(text);
    log(`  [output_transcript] "${text}"`);
  });
  session.on('control', (c) => {
    controlEvents.push(c);
    timeline.push({ type: 'control', t: Date.now() - t0 });
    log(`  [control] action=${c.action} seconds=${c.seconds} (+${Date.now() - t0}ms)`);
  });
  session.on('turnComplete', () => {
    timeline.push({ type: 'turn_complete', t: Date.now() - t0 });
    log(`  [turn_complete] (+${Date.now() - t0}ms, audio_out=${audioChunksThisTurn} chunks)`);
    audioChunksThisTurn = 0;
  });
  session.on('interrupted', () => log('  [interrupted]'));
  session.on('error', (err) => {
    sawError = true;
    console.error(`  [error] ${err.message}`);
  });
  session.on('end', () => log('  [stream end]'));

  session.sendStart({
    userId: 'smoke-test-harness',
    userTag: 'smoke-test#0000',
    channelId: 'smoke-test-control-channel',
    guildId: 'smoke-test-control-guild',
    systemPrompt: 'You are a helpful, friendly voice assistant in a live Discord voice channel.',
    recallContext: '',
    voiceName: 'Puck',
    history: [],
  });
  session.sendSpeaker(SPEAKER);

  log(`  streaming ${frames.length} frames at 20ms cadence (real-time, matches the bot)...`);
  for (const f of frames) {
    session.sendAudio(f);
    // eslint-disable-next-line no-await-in-loop
    await sleep(FRAME_MS);
  }
  session.sendAudioStreamEnd();
  log('  sendAudioStreamEnd (finalize turn)');

  log(`  collecting events for up to ${CONTROL_WAIT_MS}ms after audio end...`);
  // Wait the full window rather than stopping at the first turn_complete or
  // first control event -- for the negative fixture, "nothing arrived yet"
  // and "nothing will ever arrive" are indistinguishable until the window
  // closes, and stopping early would just be a weaker negative check.
  await Promise.race([
    sleep(CONTROL_WAIT_MS),
    waitForEvent(session, 'error', CONTROL_WAIT_MS),
  ]);

  session.end();
  await waitForEvent(session, 'end', 3000);
  session.removeAllListeners();

  const fullText = outputTranscripts.join(' ');
  const controlOk = fx.check(controlEvents);
  const ordering = fx.checkOrdering ? checkOrdering(timeline) : null;
  const pass = controlOk && (!ordering || ordering.ok);
  log(`\n  Expected: ${fx.expectDesc}`);
  log(`  Output transcript: ${outputTranscripts.length ? outputTranscripts.map((t) => `"${t}"`).join(' ') : '(none received)'}`);
  log(`  Control events received: ${controlEvents.length ? controlEvents.map((c) => `{action:"${c.action}", seconds:${c.seconds}}`).join(', ') : '(none)'}`);
  if (ordering) log(`  Ordering (control -> audio -> final turn_complete): ${ordering.ok ? 'OK' : 'VIOLATED'} -- ${ordering.why}`);
  if (sawError) log('  NOTE: session reported at least one error event -- treat this result with that in mind.');
  log(`  VERDICT (${fx.id}): ${pass ? 'PASS' : 'FAIL'}`);

  return { id: fx.id, text: fx.text, pass, transcript: fullText, controlEvents, sawError };
}

async function main() {
  log(hr('='));
  log('Voice control commands smoke test (Layer 4 -- real model, no Discord, no humans)');
  log('Exercises the MODEL-TOOL path only (end_conversation/go_quiet function calls).');
  log('The phrase backstop (services/voice/controlPhrases.js) is unit-tested separately.');
  log(hr('='));

  const files = resolveFixtures();
  log('\nFixtures:');
  FIXTURES.forEach((fx, i) => log(`  ${fx.id} -> ${files[i]}`));

  log(`\nConnecting to sidecar at ${ADDRESS} (health-polling)...`);
  const client = new VoiceClient({
    address: ADDRESS,
    protoPath: PROTO_PATH,
    healthIntervalMs: 1000,
    unhealthyThresholdMs: 5000,
    healthDeadlineMs: 2000,
  });

  const healthyDeadline = Date.now() + HEALTH_TIMEOUT_MS;
  let healthy = false;
  while (Date.now() < healthyDeadline) {
    if (client.isHealthy()) { healthy = true; break; }
    // eslint-disable-next-line no-await-in-loop
    await sleep(250);
  }
  if (!healthy) {
    console.error(`\nERROR: sidecar at ${ADDRESS} did not report healthy within ${HEALTH_TIMEOUT_MS}ms.`);
    console.error('Is the port-forward running?');
    console.error('  kubectl port-forward svc/discord-article-bot-voice 50051:50051 -n discord-article-bot &');
    console.error('Is VOICE_CONTROL_TOOLS_ENABLED=true (the default) set on the voice sidecar deployment?');
    client.close();
    process.exit(1);
  }
  log('  sidecar healthy.');

  const results = [];
  for (let i = 0; i < FIXTURES.length; i++) {
    // eslint-disable-next-line no-await-in-loop
    const r = await runFixture(client, FIXTURES[i], files[i]);
    results.push(r);
  }

  client.close();

  log(`\n${hr('=')}\nSUMMARY\n${hr('=')}`);
  for (const r of results) {
    log(`  ${r.pass ? 'PASS' : 'FAIL'}  ${r.id.padEnd(16)} "${r.text}"`);
  }
  const failed = results.filter((r) => !r.pass);
  log(hr('='));
  log(`\n${results.length - failed.length}/${results.length} passed.`);
  if (failed.length > 0) {
    log(`FAILED: ${failed.map((r) => r.id).join(', ')}`);
    if (failed.some((r) => r.id === 'ctl-negative')) {
      log('\nctl-negative FAILed: the model called a control tool on a merely superficial');
      log('phrase-lookalike ("that\'s all I know about X"). Per the Task 1 review ruling,');
      log('tighten the end_conversation tool description in the voice sidecar rather than');
      log('this script.');
    }
  }

  process.exit(failed.length > 0 ? 1 : 0);
}

main().catch((e) => {
  console.error('\nFATAL: smoke test crashed:');
  console.error(e && e.stack ? e.stack : e);
  process.exit(1);
});
