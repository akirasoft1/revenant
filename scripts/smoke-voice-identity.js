#!/usr/bin/env node
'use strict';
// Layer-4 smoke test for voice Phase 3 speaker identity (design spec
// 2026-08-14-voice-phase3-identity, "Task 7"). No Discord, no humans: it
// opens ONE real Converse session against the voice sidecar and drives a
// scripted two-speaker conversation with two distinct synthesized voices,
// then asserts on what the REAL model actually did. This exists because
// the three ways Phase 3 can fail are only observable against the real
// model:
//   1. the model reads the "[SPEAKER: <name>]" out-of-band marker aloud
//   2. the marker binds to the wrong speaker's audio
//   3. the names are never used
// None of that is unit-testable -- it needs a live Gemini Live session.
//
// Usage:
//   kubectl port-forward svc/discord-article-bot-voice 50051:50051 -n discord-article-bot &
//   node scripts/smoke-voice-identity.js [--deferral] [fileA] [fileB]
//
// With no args, uses two voice-fixtures/*.wav clips (generated by
// scripts/gen-test-voices.js, which needs GEMINI_API_KEY -- run
// automatically here if voice-fixtures/ doesn't already have >= 2 clips).
// Any two audio files ffmpeg can decode (e.g. the repo-root .m4a
// recordings) work as explicit argv overrides.
//
// --deferral (Phase 4, design spec 2026-08-14-voice-phase4-deferral, Task 5):
// runs an OPTIONAL THIRD segment after the two speaker turns below. It sends
// the AcknowledgeWaiting control event directly (bypassing VoiceService's own
// _tick trigger -- that decision logic is unit-tested elsewhere; this segment
// is real-model coverage of what the SIDECAR does with the event) as if
// Sarah (speaker B) had interjected while the bot was mid-reply, and checks
// the resulting acknowledgment: references Sarah, stays brief, never leaks
// the out-of-band `[SYSTEM: ...]` / `[SPEAKER: ...]` instruction text, and
// doesn't answer a question Sarah never actually asked in this segment.
// Without the flag, this script's behaviour is byte-identical to before.
//
// Env overrides:
//   VOICE_GRPC_ADDR         sidecar address (default 127.0.0.1:50051, i.e. a port-forward)
//   SMOKE_TURN_TIMEOUT_MS   how long to wait for a reply per speaker turn (default 25000)
//
// Exit code: non-zero ONLY on the critical MARKER SILENT failure (the
// model reading the out-of-band marker aloud, including the --deferral
// segment's `[SYSTEM:`/`[SPEAKER:` leak check) or on a harness-level
// failure (can't connect, ffmpeg missing, etc). The other checks are
// printed as PASS/FAIL but are informational -- notably NAMES USED is
// expected to legitimately FAIL against a sidecar build that predates
// SetSpeaker (see the printed sidecar-support note).
//
// IMPORTANT: this script does NOT truncate any transcript it prints.

const fs = require('fs');
const path = require('path');
const { execFileSync, spawnSync } = require('child_process');
const VoiceClient = require('../services/VoiceClient');
const VoiceService = require('../services/VoiceService');

const SAMPLE_RATE = 16000;
const FRAME_MS = 20;
const FRAME_BYTES = (SAMPLE_RATE * FRAME_MS) / 1000 * 2; // 640 bytes = 320 samples * 2 bytes (s16le)
const TRAILING_SILENCE_MS = 300; // small pad so the sidecar sees a natural pause before audio_stream_end

const FIXTURE_DIR = path.join(__dirname, '..', 'voice-fixtures');
const PROTO_PATH = path.join(__dirname, '..', 'proto', 'voice.proto');
const GEN_VOICES_SCRIPT = path.join(__dirname, 'gen-test-voices.js');

const ADDRESS = process.env.VOICE_GRPC_ADDR || '127.0.0.1:50051';
const HEALTH_TIMEOUT_MS = 8000;
const TURN_TIMEOUT_MS = Number(process.env.SMOKE_TURN_TIMEOUT_MS || 25000);
const MAX_ACK_CHARS = 200; // brevity is enforced HERE, not in the prompt (design spec Phase 4 §4)

const SPEAKERS = [
  { label: 'A', userId: 'smoke-test-speaker-A', displayName: 'Mike' },
  { label: 'B', userId: 'smoke-test-speaker-B', displayName: 'Sarah' },
];

// --deferral is a flag, not a positional arg -- strip it before fileA/fileB
// resolution so `node scripts/smoke-voice-identity.js --deferral` still
// falls back to the auto-discovered voice-fixtures/ clips instead of trying
// to treat the flag string itself as a filename.
const rawArgs = process.argv.slice(2);
const DEFERRAL_MODE = rawArgs.includes('--deferral');
const positionalArgs = rawArgs.filter((a) => a !== '--deferral');

function hr(char = '-') { return char.repeat(70); }
function log(...args) { console.log(...args); }

function sleep(ms) { return new Promise((resolve) => setTimeout(resolve, ms)); }

function waitForEvent(emitter, eventName, timeoutMs) {
  return new Promise((resolve) => {
    let done = false;
    const timer = setTimeout(() => {
      if (done) return;
      done = true;
      resolve(false);
    }, timeoutMs);
    emitter.once(eventName, () => {
      if (done) return;
      done = true;
      clearTimeout(timer);
      resolve(true);
    });
  });
}

// --- Audio decode/chunk ------------------------------------------------

function decode16kMonoS16le(file) {
  return execFileSync('ffmpeg', [
    '-v', 'error', '-i', file,
    '-ac', '1', '-ar', String(SAMPLE_RATE),
    '-f', 's16le', '-acodec', 'pcm_s16le', 'pipe:1',
  ], { maxBuffer: 1 << 28 });
}

/** Split raw PCM into 20ms/640-byte frames, matching what the bot sends.
 * A trailing partial frame is zero-padded rather than dropped -- audio
 * quality of the last <20ms doesn't matter, but silently discarding it
 * would be a lie about "the whole clip was streamed." */
function chunkFrames(pcmBuf) {
  const frames = [];
  let off = 0;
  for (; off + FRAME_BYTES <= pcmBuf.length; off += FRAME_BYTES) {
    frames.push(pcmBuf.subarray(off, off + FRAME_BYTES));
  }
  const rem = pcmBuf.length - off;
  if (rem > 0) {
    const last = Buffer.alloc(FRAME_BYTES);
    pcmBuf.copy(last, 0, off);
    frames.push(last);
  }
  return frames;
}

function silenceFrames(ms) {
  const n = Math.round(ms / FRAME_MS);
  const frames = [];
  for (let i = 0; i < n; i++) frames.push(Buffer.alloc(FRAME_BYTES));
  return frames;
}

// --- Fixture resolution --------------------------------------------------

function resolveFixtures() {
  const argA = positionalArgs[0];
  const argB = positionalArgs[1];
  if (argA && argB) {
    for (const f of [argA, argB]) {
      if (!fs.existsSync(f)) {
        console.error(`ERROR: fixture not found: ${f}`);
        process.exit(1);
      }
    }
    return { fileA: argA, fileB: argB, source: `explicit argv (${path.basename(argA)}, ${path.basename(argB)})` };
  }

  const listWavs = () => (fs.existsSync(FIXTURE_DIR)
    ? fs.readdirSync(FIXTURE_DIR).filter((f) => f.toLowerCase().endsWith('.wav')).sort()
    : []);

  let wavs = listWavs();
  if (wavs.length < 2) {
    log(`voice-fixtures/ has ${wavs.length} .wav file(s) (need >= 2) -- generating with scripts/gen-test-voices.js (requires GEMINI_API_KEY)...\n`);
    const res = spawnSync(process.execPath, [GEN_VOICES_SCRIPT], { stdio: 'inherit' });
    if (res.status !== 0) {
      console.error('\nERROR: fixture generation failed (see output above).');
      console.error('Either set GEMINI_API_KEY and retry, or pass two audio files explicitly:');
      console.error('  node scripts/smoke-voice-identity.js <fileA> <fileB>');
      process.exit(1);
    }
    wavs = listWavs();
  }
  if (wavs.length < 2) {
    console.error(`ERROR: still only ${wavs.length} fixture(s) in voice-fixtures/ after generation. Pass two audio files explicitly.`);
    process.exit(1);
  }

  // gen-test-voices.js writes named clips with distinct prebuilt TTS voices;
  // prefer the two that are actual QUESTIONS (more likely to draw a real
  // reply) over a bare statement, but fall back to "first two alphabetically"
  // if the fixture set doesn't match those exact names (e.g. regenerated).
  const preferred = ['charon-weather.wav', 'kore-joke.wav'];
  const have = preferred.filter((f) => wavs.includes(f));
  const chosen = have.length === 2 ? have : wavs.slice(0, 2);
  return {
    fileA: path.join(FIXTURE_DIR, chosen[0]),
    fileB: path.join(FIXTURE_DIR, chosen[1]),
    source: `voice-fixtures/ (${chosen.join(', ')})`,
  };
}

// --- System prompt (reuses the REAL persona-building code) --------------

function buildSystemPrompt() {
  const base = 'You are a helpful, friendly voice assistant in a live Discord voice channel.';
  // _appendVoicePersona calls this.wakeWord(), which itself just reads
  // this._config.voice.wakeWord -- so the fake `this` needs both the real
  // wakeWord() method (bound from the prototype) and the config it reads.
  // Calling the REAL prototype methods (rather than reimplementing the
  // text by hand) is what makes this exercise the actual persona-building
  // code, not a hand-copied approximation that could silently drift.
  const fakeThis = { _config: { voice: { wakeWord: 'hey jarvis' } } };
  fakeThis.wakeWord = VoiceService.prototype.wakeWord.bind(fakeThis);
  return VoiceService.prototype._appendVoicePersona.call(fakeThis, base);
}

// --- Verdict helpers -------------------------------------------------

function containsMarkerLeak(text) {
  // A real leak is the model reading an out-of-band marker aloud -- match
  // each marker's actual shape, not any bare "[", "]", or the word "speaker"
  // on its own (a reply that legitimately says "on speaker" would otherwise
  // trip this CRITICAL non-zero-exit check).
  // "[SPEAKER: <name>]" -- Phase 3 in-context speaker marker.
  if (/\[\s*SPEAKER\s*:/i.test(text)) return true;
  // "[SYSTEM: ...]" -- Phase 4 deferral-acknowledgment instruction (design
  // spec §4/§7: "never read aloud, like the [SPEAKER: ...] marker").
  if (/\[\s*SYSTEM\s*:/i.test(text)) return true;
  // Also catch the literal tag with the brackets paraphrased away, for each
  // name actually sent in marker form this run.
  return SPEAKERS.some((s) => new RegExp(`SPEAKER\\s*:\\s*${s.displayName}\\b`, 'i').test(text));
}

function mentionsName(text, name) {
  return new RegExp(`\\b${name}\\b`, 'i').test(text);
}

async function main() {
  log(hr('='));
  log('Voice Phase 3 speaker-identity smoke test (Layer 4 -- real model, no Discord, no humans)');
  log(hr('='));

  // --- Resolve + decode audio ---
  const { fileA, fileB, source } = resolveFixtures();
  log(`\nFixtures: ${source}`);
  log(`  Speaker A -> ${SPEAKERS[0].displayName}: ${fileA}`);
  log(`  Speaker B -> ${SPEAKERS[1].displayName}: ${fileB}`);

  log('\nDecoding to 16kHz mono s16le and chunking to 20ms/640B frames (ffmpeg)...');
  let framesA, framesB;
  try {
    framesA = chunkFrames(decode16kMonoS16le(fileA)).concat(silenceFrames(TRAILING_SILENCE_MS));
    framesB = chunkFrames(decode16kMonoS16le(fileB)).concat(silenceFrames(TRAILING_SILENCE_MS));
  } catch (e) {
    console.error(`\nERROR: ffmpeg decode failed: ${e.message}`);
    console.error('Is ffmpeg installed and on PATH?');
    process.exit(1);
  }
  log(`  A: ${framesA.length} frames (~${(framesA.length * FRAME_MS / 1000).toFixed(1)}s incl. trailing pad)`);
  log(`  B: ${framesB.length} frames (~${(framesB.length * FRAME_MS / 1000).toFixed(1)}s incl. trailing pad)`);

  // --- Connect ---
  log(`\nConnecting to sidecar at ${ADDRESS} (health-polling)...`);
  const client = new VoiceClient({
    address: ADDRESS,
    protoPath: PROTO_PATH,
    healthIntervalMs: 1000,
    unhealthyThresholdMs: 5000,
    healthDeadlineMs: 2000,
  });

  const healthyDeadline = Date.now() + HEALTH_TIMEOUT_MS;
  let healthy = false;
  while (Date.now() < healthyDeadline) {
    if (client.isHealthy()) { healthy = true; break; }
    await sleep(250);
  }
  if (!healthy) {
    console.error(`\nERROR: sidecar at ${ADDRESS} did not report healthy within ${HEALTH_TIMEOUT_MS}ms.`);
    console.error('Is the port-forward running?');
    console.error('  kubectl port-forward svc/discord-article-bot-voice 50051:50051 -n discord-article-bot &');
    client.close();
    process.exit(1);
  }
  log('  sidecar healthy.');

  const systemPrompt = buildSystemPrompt();
  log(`\n${hr('-')}\nsystem_prompt sent to the session (real persona-building code, roster + never-read-aloud rule included):\n${hr('-')}`);
  log(systemPrompt);
  log(hr('-'));

  // --- Open the session and wire up event collection ---
  const session = client.converse();

  // currentSpeakerTag is updated the instant we CALL sendSpeaker (mirrors
  // VoiceService: it also just fires-and-forgets sendSpeaker before
  // streaming that speaker's audio). Any input_transcript arriving after
  // that point is tagged with this value for the human-eyeball attribution
  // check below. This is a best-effort local label, not proof of what the
  // model itself bound the audio to -- send_realtime_input ordering against
  // send_client_content is not guaranteed (see live_bridge.py's comment on
  // the marker-send site), which is exactly why this needs a real session
  // to observe rather than being provable from the code alone.
  let currentSpeakerTag = '(none yet)';
  const inputTranscripts = []; // {speaker, text}
  const outputTranscripts = []; // text
  let turnCompleteCount = 0;
  let outputAudioBytes = 0;
  let sawError = false;

  session.on('inputTranscript', (text) => {
    inputTranscripts.push({ speaker: currentSpeakerTag, text });
    log(`  [input_transcript] (${currentSpeakerTag}) "${text}"`);
  });
  session.on('outputTranscript', (text) => {
    outputTranscripts.push(text);
    log(`  [output_transcript] "${text}"`);
  });
  session.on('audio', (buf) => { outputAudioBytes += buf.length; });
  session.on('turnComplete', () => {
    turnCompleteCount++;
    log(`  [turn_complete] (#${turnCompleteCount} overall)`);
  });
  session.on('interrupted', () => log('  [interrupted]'));
  session.on('error', (err) => {
    sawError = true;
    console.error(`  [error] ${err.message}`);
  });
  session.on('end', () => log('  [stream end]'));

  log('\nsendStart...');
  session.sendStart({
    userId: 'smoke-test-harness',
    userTag: 'smoke-test#0000',
    channelId: 'smoke-test-channel',
    guildId: 'smoke-test-guild',
    systemPrompt,
    recallContext: '',
    voiceName: 'Puck',
    history: [],
  });

  const perSpeakerResults = [];
  // --deferral segment 3 verdicts; stay `null` (and get skipped in the
  // SUMMARY section) when the flag isn't passed.
  let deferralRan = false;
  let deferralText = '';
  let deferralTurnsThisSegment = 0;
  let deferralReferencesSarahPass = null;
  let deferralBriefPass = null;
  let deferralNoLeakPass = null;

  for (const [i, spk] of SPEAKERS.entries()) {
    const frames = i === 0 ? framesA : framesB;
    log(`\n${hr('-')}\nSpeaker ${spk.label} (${spk.displayName})\n${hr('-')}`);
    currentSpeakerTag = `${spk.label}/${spk.displayName}`;
    session.sendSpeaker({ userId: spk.userId, displayName: spk.displayName });
    log(`  sendSpeaker({ userId: '${spk.userId}', displayName: '${spk.displayName}' })`);

    const turnsBefore = turnCompleteCount;
    const audioBytesBefore = outputAudioBytes;

    log(`  streaming ${frames.length} frames at 20ms cadence (real-time, matches the bot)...`);
    for (const f of frames) {
      session.sendAudio(f);
      await sleep(FRAME_MS);
    }
    session.sendAudioStreamEnd();
    log('  sendAudioStreamEnd (finalize turn)');

    log(`  waiting up to ${TURN_TIMEOUT_MS}ms for turn_complete...`);
    const got = await waitForEvent(session, 'turnComplete', TURN_TIMEOUT_MS);
    if (!got) {
      log('  WARNING: no turn_complete observed within the timeout -- proceeding anyway.');
    } else {
      // Small grace period: audio/output_transcript events for the tail of
      // the reply can trail the turn_complete event slightly.
      await sleep(500);
    }

    const turnsThisSegment = turnCompleteCount - turnsBefore;
    const audioBytesThisSegment = outputAudioBytes - audioBytesBefore;
    log(`  segment result: turn_complete x${turnsThisSegment}, ${audioBytesThisSegment} bytes of output audio`);
    perSpeakerResults.push({ ...spk, turnsThisSegment, audioBytesThisSegment });
  }

  // --- Segment 3 (--deferral only): AcknowledgeWaiting for a withheld speaker ---
  if (DEFERRAL_MODE) {
    deferralRan = true;
    log(`\n${hr('-')}\nSegment 3 (--deferral): AcknowledgeWaiting({ displayName: 'Sarah' })\n${hr('-')}`);
    log('  Sends the control event directly, as if Sarah (speaker B) had interjected while');
    log('  the bot was mid-reply -- no new audio is streamed for her in this segment, so any');
    log('  substantive answer content in the reply would mean the model is answering a');
    log('  question Sarah never actually asked here.');

    const turnsBefore = turnCompleteCount;
    const outputsBefore = outputTranscripts.length;

    // The send reports whether the write went out. Don't log success for a
    // nudge the client already knows it dropped -- this is the only real-model
    // path that exercises the ack, so a silent false here would read as "the
    // model ignored it" when in fact nothing was ever sent.
    const ackSent = session.sendAcknowledgeWaiting({ displayName: 'Sarah' });
    if (ackSent === false) {
      log("  sendAcknowledgeWaiting({ displayName: 'Sarah' }) -> CLIENT REPORTED THE WRITE DID NOT GO OUT");
      log('  Every DEFERRAL check below is therefore meaningless -- the sidecar never received');
      log('  the nudge, so an absent reply says nothing about the model. Fix the stream first.');
    } else {
      log("  sendAcknowledgeWaiting({ displayName: 'Sarah' }) -> sent");
    }

    log(`  waiting up to ${TURN_TIMEOUT_MS}ms for turn_complete...`);
    const got = await waitForEvent(session, 'turnComplete', TURN_TIMEOUT_MS);
    if (!got) {
      log('  WARNING: no turn_complete observed within the timeout -- proceeding anyway.');
    } else {
      await sleep(500); // trailing audio/output_transcript events can lag turn_complete slightly
    }

    deferralTurnsThisSegment = turnCompleteCount - turnsBefore;
    const deferralTranscripts = outputTranscripts.slice(outputsBefore);
    deferralText = deferralTranscripts.join(' ');
    log(`  acknowledgment reply: ${deferralTranscripts.length ? deferralTranscripts.map((t) => `"${t}"`).join(' ') : '(no output transcript received)'}`);
    log(`  segment result: turn_complete x${deferralTurnsThisSegment}, ${deferralText.length} chars of transcript`);

    deferralReferencesSarahPass = mentionsName(deferralText, 'Sarah');
    deferralBriefPass = deferralText.length > 0 && deferralText.length < MAX_ACK_CHARS;
    deferralNoLeakPass = !deferralTranscripts.some((t) => containsMarkerLeak(t));
  }

  log(`\n${hr('-')}\nsendSessionEnd / close\n${hr('-')}`);
  session.end();
  await waitForEvent(session, 'end', 3000);
  client.close();

  // --- Verdicts ---
  log(`\n${hr('=')}\nVERDICTS\n${hr('=')}`);

  // 1. MARKER SILENT (critical)
  const leaks = outputTranscripts.filter(containsMarkerLeak);
  const markerSilentPass = leaks.length === 0;
  log(`\nMARKER SILENT (critical): ${markerSilentPass ? 'PASS' : 'FAIL'}`);
  log('  No output transcript may contain "SPEAKER", "[", "]", or the literal marker text.');
  if (!markerSilentPass) {
    log(`  FAIL -- ${leaks.length} output transcript(s) leaked marker text:`);
    for (const t of leaks) log(`    - "${t}"`);
  } else {
    log(`  Checked ${outputTranscripts.length} output transcript(s); none leaked marker text.`);
  }

  // 2. NAMES USED
  const nameHits = outputTranscripts.filter((t) => mentionsName(t, 'Mike') || mentionsName(t, 'Sarah'));
  const namesUsedPass = nameHits.length > 0;
  log(`\nNAMES USED: ${namesUsedPass ? 'PASS' : 'FAIL'}`);
  log('  At least one output transcript should mention "Mike" or "Sarah".');
  if (namesUsedPass) {
    for (const t of nameHits) log(`    - "${t}"`);
  } else {
    log('  FAIL -- no output transcript mentioned either name. If the sidecar in use predates');
    log('  SetSpeaker (proto field 5), it silently ignores set_speaker events -- this is the');
    log('  EXPECTED result against that build, not evidence of a Phase 3 bug in the bot/proto.');
  }

  // 3. NO DOUBLE-ANSWER
  const doubleAnswerSegments = perSpeakerResults.filter((r) => r.turnsThisSegment > 1);
  const noDoubleAnswerPass = doubleAnswerSegments.length === 0;
  log(`\nNO DOUBLE-ANSWER: ${noDoubleAnswerPass ? 'PASS' : 'FAIL'}`);
  log('  Each speaker turn should produce exactly one turn_complete (a single full reply).');
  log('  NOTE: a FAIL here is only meaningful if the clip is ONE continuous utterance.');
  log('  A pre-recorded clip with a natural pause (e.g. "Hey Jarvis." ... "what is the');
  log('  weather?") is legitimately split into two turns by the server VAD, producing two');
  log('  answers. Check the ATTRIBUTION list below: if one speaker shows two DIFFERENT');
  log('  input transcripts, the split is correct behaviour, not the double-answer bug.');
  for (const r of perSpeakerResults) {
    log(`    - Speaker ${r.label} (${r.displayName}): turn_complete x${r.turnsThisSegment}, ${r.audioBytesThisSegment} bytes audio${r.turnsThisSegment > 1 ? '  <-- DOUBLE ANSWER' : ''}`);
  }
  log(`  Total turn_complete events across the whole session: ${turnCompleteCount}`);

  // 4. ATTRIBUTION SANITY (human-eyeball; verdict = "was there data to eyeball")
  log(`\nATTRIBUTION SANITY: ${inputTranscripts.length > 0 ? 'DATA PRESENT (eyeball below)' : 'NO DATA (nothing transcribed -- cannot assess)'}`);
  log('  Each input transcript, tagged with whichever speaker we told the sidecar was current');
  log('  when it arrived. A human should confirm A\'s words are tagged A and B\'s are tagged B.');
  if (inputTranscripts.length === 0) {
    log('  No input transcripts were received at all -- either the model produced none, or the');
    log('  session never got far enough to transcribe input. See sawError / event log above.');
  } else {
    for (const it of inputTranscripts) {
      log(`    [${it.speaker}] "${it.text}"`);
    }
    const sawA = inputTranscripts.some((it) => it.speaker.startsWith('A/'));
    const sawB = inputTranscripts.some((it) => it.speaker.startsWith('B/'));
    if (!sawA || !sawB) {
      log(`  NOTE: only received input transcripts while speaker tag was ${sawA ? 'A' : 'B'} -- `
        + 'the other speaker\'s utterance produced no input_transcript event to eyeball.');
    }
  }

  // 5. DEFERRAL ACKNOWLEDGMENT (--deferral only)
  if (deferralRan) {
    log(`\nDEFERRAL REFERENCES SARAH: ${deferralReferencesSarahPass ? 'PASS' : 'FAIL'}`);
    log('  The acknowledgment reply should mention "Sarah" by name.');

    log(`\nDEFERRAL IS BRIEF: ${deferralBriefPass ? 'PASS' : 'FAIL'}`);
    log(`  Acknowledgment transcript must be non-empty and under ${MAX_ACK_CHARS} chars`);
    log(`  (brevity is enforced HERE, not in the prompt -- design spec Phase 4 §4). Got ${deferralText.length} chars.`);

    log(`\nDEFERRAL NO MARKER LEAK (critical): ${deferralNoLeakPass ? 'PASS' : 'FAIL'}`);
    log('  The acknowledgment must not contain "[SYSTEM:" or "[SPEAKER:" -- those are');
    log('  out-of-band instructions, never read aloud.');

    // "Does not answer a question Sarah never asked": no audio was streamed for
    // her in this segment, so there is no real question to check the reply
    // against -- this can't be verified by string-matching the reply against
    // content it was never given. Exactly one turn_complete + staying under the
    // brevity bound is the closest mechanical proxy (a real Q&A answer is very
    // unlikely to fit both); the actual transcript is printed above for a human
    // to eyeball directly, same pattern as ATTRIBUTION SANITY below.
    const deferralNoDoubleAnswerPass = deferralTurnsThisSegment === 1;
    log(`\nDEFERRAL NO UNASKED ANSWER (eyeball, mechanical proxy): ${deferralNoDoubleAnswerPass ? 'PASS (single, brief turn)' : `FAIL (${deferralTurnsThisSegment} turn_complete events)`}`);
    log('  Proxy only -- exactly one turn_complete for this segment. A human should confirm');
    log('  the printed acknowledgment text above reads as "noticed you, one sec" and not as');
    log('  an answer to some invented question.');
  }

  if (sawError) {
    log('\nNOTE: the session reported at least one error event (see [error] lines above) --');
    log('treat all verdicts with that in mind.');
  }
  if (turnCompleteCount === 0 && outputAudioBytes === 0 && outputTranscripts.length === 0) {
    log('\nWARNING: the sidecar produced NO output at all (no transcript, no audio, no');
    log('turn_complete) across either speaker turn. That is a harness/connectivity/model');
    log('problem independent of speaker identity -- check the sidecar logs before trusting');
    log('the PASS results above (an empty transcript set trivially passes MARKER SILENT).');
  }

  log(`\n${hr('=')}\nSUMMARY\n${hr('=')}`);
  log(`  MARKER SILENT (critical) : ${markerSilentPass ? 'PASS' : 'FAIL'}`);
  log(`  NAMES USED               : ${namesUsedPass ? 'PASS' : 'FAIL'}`);
  log(`  NO DOUBLE-ANSWER          : ${noDoubleAnswerPass ? 'PASS' : 'FAIL'}`);
  log(`  ATTRIBUTION SANITY        : ${inputTranscripts.length > 0 ? 'DATA PRESENT (see above)' : 'NO DATA'}`);
  if (deferralRan) {
    log(`  DEFERRAL REFERENCES SARAH : ${deferralReferencesSarahPass ? 'PASS' : 'FAIL'}`);
    log(`  DEFERRAL IS BRIEF         : ${deferralBriefPass ? 'PASS' : 'FAIL'}`);
    log(`  DEFERRAL NO MARKER LEAK   : ${deferralNoLeakPass ? 'PASS' : 'FAIL'}  (critical)`);
    log(`  DEFERRAL NO UNASKED ANSWER: ${deferralTurnsThisSegment === 1 ? 'PASS (proxy)' : 'FAIL (proxy)'}`);
  }
  log(hr('='));

  if (!markerSilentPass) {
    console.error('\nCRITICAL FAILURE: the model read the speaker marker aloud. Exiting non-zero.');
    process.exit(1);
  }
  process.exit(0);
}

main().catch((e) => {
  console.error('\nFATAL: smoke test crashed:');
  console.error(e && e.stack ? e.stack : e);
  process.exit(1);
});
